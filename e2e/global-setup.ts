import { execSync } from "node:child_process";

/**
 * Сид перед прогоном.
 *
 * Без него тесты накапливают данные друг за другом и за прошлыми запусками:
 * занятые слоты, проданные абонементы, платежи. Прогон, который проходит
 * с первого раза и падает со второго, хуже отсутствующего — он приучает
 * не верить красному.
 *
 * Отключён отправкой уведомлений: сид создаёт три десятка записей, и письма
 * по каждой из них засорили бы почтовый ящик, из которого тесты читают
 * ссылки для входа.
 */
export default function globalSetup() {
  if (process.env.E2E_SKIP_SEED === "true") return;

  console.info("E2E: засеиваю базу");

  execSync("npx tsx prisma/seed.ts", {
    stdio: "inherit",
    env: { ...process.env, DISABLE_NOTIFICATIONS: "true" },
  });
}
